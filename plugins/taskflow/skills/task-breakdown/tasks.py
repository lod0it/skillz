def _write_status(task, mark, text):
    status = f"{mark} {text}".rstrip()
    task.path.write_text(set_field(task.text, "Status", status), encoding="utf-8")


def cmd_move(board, args):
    task = find_task(board, args.id)
    stage = resolve_stage(args.stage)
    if args.rejected and stage is not DONE:
        raise SystemExit("--rejected only applies to `done`")
    mark = "[-]" if args.rejected else stage.mark
    if args.note:
        text = args.note
    elif stage is task.stage and not args.rejected:
        text = task.status_text
    else:
        text = "rejected" if args.rejected else stage.text
    _write_status(task, mark, text)
    dst = board.tasks_dir / stage.folder / task.path.name
    if dst != task.path:
        relocate(board.root, task.path, dst)
    board = Board(board.root)
    refresh_index(board)
    print(f"Task {task.id}: {board.rel(dst)}  {mark} {text}")
    return 0


def cmd_adopt(board, args):
    src = Path(args.path)
    src = src if src.is_absolute() else (board.root / src)
    if not src.is_file():
        raise SystemExit(f"{args.path}: no such file")
    stage = resolve_stage(args.stage)
    name = src.name
    if stage is not DONE:
        m = FILE_RE.match(name)
        if not m:
            raise SystemExit(f"{name}: cannot find a task id at the start of the name")
        name = f"{m.group(1)}_{re.sub(r'[^a-z0-9]+', '_', m.group(2).lower()).strip('_')}.md"
        task = Task(src, stage)
        _write_status(task, stage.mark, task.status_text or stage.text)
    dst = board.tasks_dir / stage.folder / name
    relocate(board.root, src, dst)
    print(f"adopted {board.rel(dst)}")
    return 0


def cmd_set(board, args):
    task = find_task(board, args.id)
    if task.stage is DONE:
        raise SystemExit(f"Task {task.id} is closed: closed tasks are history")
    key = next((k for k in FIELD_ORDER if k.lower() == args.field.lower()), args.field)
    if key == "Status":
        raise SystemExit("the Status line belongs to `move` (use --note for its text)")
    task.path.write_text(set_field(task.text, key, args.value), encoding="utf-8")
    refresh_index(Board(board.root))
    print(f"Task {task.id}: {key} = {args.value}")
    return 0


