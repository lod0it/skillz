#!/usr/bin/env python3
"""Zero-token bookkeeping for a tasks/ pipeline.

The task files are the source of truth: a task's stage is the folder it sits
in, its metadata is the `**Key:** value` block under its title. The index in
TASKS.md and tasks/99_done/INDEX.md are generated from them, never hand-edited.

Standard library only. Usage: tasks.py <command> [--root DIR]; see --help.
"""

import argparse
import fnmatch
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import NamedTuple


class Stage(NamedTuple):
    name: str
    folder: str
    mark: str
    text: str
    label: str


STAGES = (
    Stage("backlog", "00_backlog", "[ ]", "on hold: out of the Loop", "Backlog"),
    Stage("to-grill", "01_to-grill", "[ ]", "to grill: decisions before any code", "To grill"),
    Stage("design-gate", "02_design-gate", "[ ]", "design gate: approval before code", "Design gate"),
    Stage("ready", "03_ready", "[ ]", "not started", "Ready"),
    Stage("real-check", "04_real-check", "[ ]", "tell the user first", "Real check"),
    Stage("to-be-tested", "05_to-be-tested", "[~]", "code done; manual check pending", "To be tested"),
    Stage("done", "99_done", "[x]", "done", "Done"),
)
DONE = STAGES[-1]
OPEN_STAGES = STAGES[:-1]
INDEX_STAGES = OPEN_STAGES[1:] + OPEN_STAGES[:1]  # the backlog last: it is not active work
STAGE_ALIASES = {"hold": "backlog", "grill": "to-grill", "design": "design-gate", "check": "real-check",
                 "test": "to-be-tested", "tested": "to-be-tested"}

INDEX_START = "<!-- task-index:start (generated by tasks.py: edit the task files, not this block) -->"
INDEX_END = "<!-- task-index:end -->"
DONE_INDEX = "INDEX.md"
KEPT_IN_TASKS_ROOT = {"archive.md", ".gitkeep", ".DS_Store"}

FIELD_ORDER = ("Status", "Type", "Depends on", "Who", "Files")
DEFAULT_TYPES = ("feature", "bug", "polish")
NOTHING = {"", "—", "–", "-", "none", "n/a"}
NOTHING_TO_CHECK = "nothing to check by hand"
STATUS_MAX = 120

ID = r"\d+[a-z]?"
TITLE_RE = re.compile(rf"^# Task ({ID})\s*[:—–-]\s*(.+?)\s*$")
FIELD_RE = re.compile(r"^\*\*([^*:]+):\*\*\s*(.*)$")
STATUS_RE = re.compile(r"^\[([ ~x-])\]\s*(.*)$")
FILE_RE = re.compile(rf"^({ID})[_-](.+)\.md$")
OPEN_FILE_RE = re.compile(rf"^{ID}_[a-z0-9_]+\.md$")
DEP_ITEM_RE = re.compile(rf"^(?:Tasks?\s+)?({ID})$")
CONFIG_RE = re.compile(r"^[-*]\s+\*\*([^*:]+):\*\*\s*(.*)$")


def id_key(task_id):
    m = re.match(r"(\d+)([a-z]?)", task_id)
    return (int(m.group(1)), m.group(2))


def parse_depends(value):
    """`Task 93a, Task 74c (same file)` -> (["93a", "74c"], None). Strict:
    anything that is not a comma-separated list of ids is an error."""
    value = re.sub(r"\([^)]*\)", "", value).strip()
    if value.lower() in NOTHING:
        return [], None
    ids = []
    for item in value.split(","):
        m = DEP_ITEM_RE.match(item.strip())
        if not m:
            return [], f"cannot read `{item.strip()}` (write `Task 12, Task 13b`, notes in brackets)"
        ids.append(m.group(1))
    return ids, None


def paths_overlap(a, b):
    if a == b or fnmatch.fnmatch(a, b) or fnmatch.fnmatch(b, a):
        return True
    return (a.endswith("/") and b.startswith(a)) or (b.endswith("/") and a.startswith(b))


class Task:
    def __init__(self, path, stage):
        self.path = path
        self.stage = stage
        self.fields = {}
        self.title = None
        self.title_id = None
        m = FILE_RE.match(path.name)
        self.file_id = m.group(1) if m else None
        self.text = path.read_text(encoding="utf-8")
        self.sections = {}
        section = None
        for line in self.text.splitlines():
            if line.startswith("## "):
                section = line[3:].strip().lower()
                self.sections[section] = []
            elif section is not None:
                self.sections[section].append(line)
            else:
                m = TITLE_RE.match(line)
                if m and self.title is None:
                    self.title_id, self.title = m.group(1), m.group(2)
                    continue
                m = FIELD_RE.match(line)
                if m:
                    self.fields.setdefault(m.group(1).strip().lower(), m.group(2).strip())
        if self.title is None:
            m = FILE_RE.match(path.name)
            self.title = (m.group(2) if m else path.stem).replace("_", " ")
        self.id = self.title_id or self.file_id or path.stem
        status = self.fields.get("status", "")
        m = STATUS_RE.match(status)
        self.mark = f"[{m.group(1)}]" if m else None
        self.status_text = m.group(2) if m else status
        self.depends, self.depends_error = parse_depends(self.fields.get("depends on", ""))
        self.files = re.findall(r"`([^`]+)`", self.fields.get("files", ""))
        self.who = self.fields.get("who", "")
        self.type = self.fields.get("type", "")

    def section(self, name):
        return "\n".join(self.sections.get(name, [])).strip()

    def overlaps(self, other):
        return sorted({a for a in self.files for b in other.files if paths_overlap(a, b)})


class Board:
    def __init__(self, root):
        self.root = Path(root)
        self.tasks_dir = self.root / "tasks"
        self.tasks_md = self.root / "TASKS.md"
        self.config = self._load_config()
        self.open = []
        self.closed = []
        for stage in STAGES:
            folder = self.tasks_dir / stage.folder
            if not folder.is_dir():
                continue
            for path in sorted(folder.glob("*.md")):
                if stage is DONE and path.name == DONE_INDEX:
                    continue
                (self.closed if stage is DONE else self.open).append(Task(path, stage))
        self.open.sort(key=lambda t: _safe_key(t.id))
        self.closed.sort(key=lambda t: _safe_key(t.id))
        self.open_by_id = {t.id: t for t in self.open}
        self.closed_ids = {t.id for t in self.closed}

    def rel(self, path):
        return Path(path).relative_to(self.root).as_posix()

    def _load_config(self):
        cfg = {}
        if not self.tasks_md.is_file():
            return cfg
        in_section = False
        for line in self.tasks_md.read_text(encoding="utf-8").splitlines():
            if line.startswith("## "):
                in_section = line[3:].strip().lower() == "task system"
            elif in_section and (m := CONFIG_RE.match(line)):
                cfg[m.group(1).strip().lower()] = m.group(2).strip()
        return cfg

    def config_list(self, key, default=()):
        value = re.sub(r"\([^)]*\)", "", self.config.get(key, "")).strip()
        if value.lower() in NOTHING:
            return list(default)
        return [item.strip().strip("`") for item in value.split(",") if item.strip()]

    def config_code(self, key):
        """The first `backticked` token of a config value, or None."""
        m = re.search(r"`([^`]+)`", self.config.get(key, ""))
        return m.group(1) if m else None

    def archived_numbers(self):
        numbers = set()
        value = re.sub(r"\([^)]*\)", "", self.config.get("archived ids", ""))
        for lo, hi in re.findall(r"(\d+)\s*(?:[-–]\s*(\d+))?", value):
            numbers.update(range(int(lo), int(hi or lo) + 1))
        return numbers

    def dep_state(self, dep):
        """done | open | unknown. A task waiting only for the user's manual
        check counts as done for whoever depends on it."""
        task = self.open_by_id.get(dep)
        if task:
            return "done" if task.stage.name == "to-be-tested" else "open"
        if dep in self.closed_ids or id_key(dep)[0] in self.archived_numbers():
            return "done"
        return "unknown"

    def waits_for(self, task):
        return [d for d in task.depends if self.dep_state(d) != "done"]

    def depends_transitively(self, task, other_id, seen=None):
        seen = seen or set()
        for dep in task.depends:
            if dep == other_id:
                return True
            if dep in seen or dep not in self.open_by_id:
                continue
            seen.add(dep)
            if self.depends_transitively(self.open_by_id[dep], other_id, seen):
                return True
        return False

    def in_stage(self, name):
        return [t for t in self.open if t.stage.name == name]


def _safe_key(task_id):
    return id_key(task_id) if re.fullmatch(ID, task_id) else (10**9, task_id)


def find_root(start):
    start = Path(start).resolve()
    for folder in (start, *start.parents):
        if (folder / "TASKS.md").is_file() or (folder / "tasks").is_dir():
            return folder
    return start


def resolve_stage(word):
    word = STAGE_ALIASES.get(word.lower(), word.lower())
    for stage in STAGES:
        if word in (stage.name, stage.folder, stage.folder[:2]):
            return stage
    names = ", ".join(s.name for s in STAGES)
    raise SystemExit(f"unknown stage `{word}` (one of: {names})")


# --- index -----------------------------------------------------------------

def _cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def _short(text):
    return text if len(text) <= STATUS_MAX else text[: STATUS_MAX - 1].rstrip() + "…"


def render_index(board):
    counts = " · ".join(f"{s.label.lower()} {len(board.in_stage(s.name))}" for s in INDEX_STAGES)
    lines = [INDEX_START,
             f"Open: {len(board.open)} ({counts}). "
             f"Closed: {len(board.closed)}, listed in `tasks/{DONE.folder}/{DONE_INDEX}`.",
             ""]
    for stage in INDEX_STAGES:
        tasks = board.in_stage(stage.name)
        lines.append(f"### {stage.folder[:2]} {stage.label} ({len(tasks)})")
        if not tasks:
            lines += ["None.", ""]
            continue
        lines += ["| Task | File | Status | Waits for | Type | Who |", "|---|---|---|---|---|---|"]
        for t in tasks:
            waits = ", ".join(board.waits_for(t)) or "—"
            lines.append(f"| {t.id} {_cell(t.title)} | `{board.rel(t.path)}` | {_cell(_short(t.status_text)) or '—'} "
                         f"| {waits} | {t.type or '—'} | {t.who or '—'} |")
        lines.append("")
    lines.append(INDEX_END)
    return "\n".join(lines)


def render_done_index(board):
    lines = ["# Closed tasks", "",
             "Generated by `tasks.py index`. History, one row per closed task: read it only when a task points here.",
             "", "| Task | File | Status |", "|---|---|---|"]
    for t in board.closed:
        status = " ".join(x for x in (t.mark, _short(t.status_text)) if x)
        lines.append(f"| {t.id} {_cell(t.title)} | `{t.path.name}` | {_cell(status) or '—'} |")
    return "\n".join(lines) + "\n"


def _index_span(text):
    lines = text.splitlines(keepends=True)
    start = next((i for i, l in enumerate(lines) if l.startswith("<!-- task-index:start")), None)
    end = next((i for i, l in enumerate(lines) if l.startswith("<!-- task-index:end")), None)
    if start is None or end is None or end < start:
        return None
    return lines, start, end


def index_problems(board):
    if not board.tasks_md.is_file():
        return ["TASKS.md is missing (run `init`)"]
    span = _index_span(board.tasks_md.read_text(encoding="utf-8"))
    if span is None:
        return ["TASKS.md has no task-index markers (add the two marker lines where the index goes, then run `index`)"]
    lines, start, end = span
    current = "".join(lines[start:end + 1]).rstrip("\n")
    problems = []
    if current != render_index(board):
        problems.append("the index in TASKS.md is stale (run `index`)")
    done_index = board.tasks_dir / DONE.folder / DONE_INDEX
    if not done_index.is_file() or done_index.read_text(encoding="utf-8") != render_done_index(board):
        problems.append(f"tasks/{DONE.folder}/{DONE_INDEX} is stale (run `index`)")
    return problems


def refresh_index(board):
    """After an edit: rewrite the index when TASKS.md can hold one. A repo in
    the middle of a migration has no markers yet, and the edit still stands."""
    if board.tasks_md.is_file() and _index_span(board.tasks_md.read_text(encoding="utf-8")):
        write_index(board)
    else:
        print("index not rewritten: TASKS.md has no task-index markers yet")


def write_index(board):
    if not board.tasks_md.is_file():
        raise SystemExit("TASKS.md is missing (run `init`)")
    text = board.tasks_md.read_text(encoding="utf-8")
    span = _index_span(text)
    if span is None:
        raise SystemExit("TASKS.md has no task-index markers: add these two lines where the index goes\n"
                         f"{INDEX_START}\n{INDEX_END}")
    lines, start, end = span
    new = "".join(lines[:start]) + render_index(board) + "\n" + "".join(lines[end + 1:])
    if new != text:
        board.tasks_md.write_text(new, encoding="utf-8")
    done_dir = board.tasks_dir / DONE.folder
    if done_dir.is_dir():
        (done_dir / DONE_INDEX).write_text(render_done_index(board), encoding="utf-8")


